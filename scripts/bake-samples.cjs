// Added in Beepbox Reborn. Turns the recordings listed in samples/manifest.json
// into editor/BakedSamples.ts, which registers them under "Sampled Instruments"
// when the editor or player starts. Runs before every editor/player compile.
//
// Manifest entry: {"name": "Trumpet", "file": "trumpet.wav", "rootKey": 60,
//   "loopStart": 12000, "loopEnd": 30000, "drum": false}
// Only name and file are required. rootKey (MIDI note the recording was played
// at; decimals allowed) is measured when left out, and the build stops if the
// measurement is ambiguous. loopStart/loopEnd are in frames of the original file.
// drum: true lists it in the drum menu instead (rootKey then defaults to 60).
//
// Audio is stored mono, 16-bit, peak-normalized, with silence trimmed.

const fs = require("fs");
const path = require("path");
const {readWav, measurePitch} = require("./measure-pitch.cjs");

const root = path.resolve(__dirname, "..");
const samplesDir = path.join(root, "samples");
const manifestPath = path.join(samplesDir, "manifest.json");
const outputPath = path.join(root, "editor", "BakedSamples.ts");

const header = "// GENERATED by scripts/bake-samples.cjs from samples/manifest.json. Do not edit.\n";

function fail(message) {
	console.error("bake-samples: " + message);
	process.exit(1);
}

function trimAndEncode(entry, sampleRate, data) {
	let peak = 0;
	for (let i = 0; i < data.length; i++) peak = Math.max(peak, Math.abs(data[i]));
	if (!(peak > 0)) fail(entry.file + " is silent.");
	const threshold = peak * Math.pow(10, -50 / 20);
	const looped = entry.loopStart != undefined || entry.loopEnd != undefined;
	if (looped && !(Number.isInteger(entry.loopStart) && Number.isInteger(entry.loopEnd) && entry.loopStart >= 0 && entry.loopEnd > entry.loopStart && entry.loopEnd <= data.length)) {
		fail("\"" + entry.name + "\" needs whole-number loopStart and loopEnd with loopStart < loopEnd <= " + data.length + " (frames).");
	}
	let first = 0;
	while (first < data.length && Math.abs(data[first]) < threshold) first++;
	let last = data.length - 1;
	while (last > first && Math.abs(data[last]) < threshold) last--;
	let start = Math.max(0, first - Math.round(sampleRate * 0.005));
	let end = Math.min(data.length, last + 1 + Math.round(sampleRate * 0.02));
	if (looped) {
		start = Math.min(start, entry.loopStart);
		end = entry.loopEnd; // nothing after the loop is ever heard
	}
	const length = end - start;
	const fadeLength = looped ? 0 : Math.min(length, Math.round(sampleRate * 0.01));
	const pcm = Buffer.alloc(length * 2);
	for (let i = 0; i < length; i++) {
		let value = data[start + i] / peak;
		if (i >= length - fadeLength) value *= (length - i) / fadeLength;
		pcm.writeInt16LE(Math.max(-32768, Math.min(32767, Math.round(value * 32767))), i * 2);
	}
	return {
		pcm: pcm.toString("base64"),
		frames: length,
		loopStart: looped ? entry.loopStart - start : undefined,
		loopEnd: looped ? entry.loopEnd - start : undefined,
	};
}

function main() {
	let manifest = [];
	if (fs.existsSync(manifestPath)) {
		try {
			manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
		} catch (error) {
			fail("samples/manifest.json is not valid JSON: " + error.message);
		}
	}
	if (!Array.isArray(manifest)) fail("samples/manifest.json must be a list of entries.");

	const names = new Set();
	const recordings = [];
	for (const entry of manifest) {
		if (typeof entry.name != "string" || entry.name.trim() == "") fail("Every manifest entry needs a \"name\".");
		if (names.has(entry.name)) fail("Two manifest entries are both named \"" + entry.name + "\".");
		names.add(entry.name);
		if (typeof entry.file != "string") fail("\"" + entry.name + "\" needs a \"file\".");
		const filePath = path.resolve(samplesDir, entry.file);
		if (path.relative(samplesDir, filePath).startsWith("..")) fail("\"" + entry.name + "\": the file must be inside samples/.");
		if (!fs.existsSync(filePath)) fail("\"" + entry.name + "\": samples/" + entry.file + " doesn't exist.");

		const {sampleRate, data} = readWav(filePath);
		let rootKey = entry.rootKey;
		if (rootKey == undefined) {
			if (entry.drum) {
				rootKey = 60;
			} else {
				const measured = measurePitch(data, sampleRate);
				if (measured.ambiguous) {
					fail("Couldn't tell which note \"" + entry.name + "\" was played at: " + measured.reason + "." + (measured.midi != undefined ? " Best guess " + measured.note + " (" + measured.midi + ")." : "") + " Add \"rootKey\" to its manifest entry.");
				}
				rootKey = measured.midi;
				console.log("bake-samples: \"" + entry.name + "\" measured at " + measured.note + " " + (measured.cents >= 0 ? "+" : "") + measured.cents + " cents (rootKey " + rootKey + ").");
			}
		}
		if (typeof rootKey != "number" || !isFinite(rootKey)) fail("\"" + entry.name + "\": rootKey must be a number.");

		const encoded = trimAndEncode(entry, sampleRate, data);
		const seconds = encoded.frames / sampleRate;
		console.log("bake-samples: \"" + entry.name + "\" " + seconds.toFixed(2) + " s, " + encoded.pcm.length + " bytes (" + Math.round(encoded.pcm.length / seconds) + " bytes/s).");
		recordings.push({name: entry.name, isNoise: entry.drum == true, rootKey, sampleRate, loopStart: encoded.loopStart, loopEnd: encoded.loopEnd, pcm: encoded.pcm});
	}

	let output;
	if (recordings.length == 0) {
		output = header + "// No recordings are listed, so nothing is added to the build.\nexport {};\n";
	} else {
		output = header + `
import {SampleRegistry} from "../synth/SampleRegistry.js";

interface BakedRecording {
	readonly name: string;
	readonly isNoise: boolean;
	readonly rootKey: number;
	readonly sampleRate: number;
	readonly loopStart?: number;
	readonly loopEnd?: number;
	readonly pcm: string; // base64, 16-bit little-endian mono
}

function decode(base64: string): Float32Array {
	const binary: string = atob(base64);
	const data: Float32Array = new Float32Array(binary.length >> 1);
	for (let i: number = 0; i < data.length; i++) {
		const value: number = binary.charCodeAt(i * 2) | (binary.charCodeAt(i * 2 + 1) << 8);
		data[i] = ((value & 0x8000) ? value - 0x10000 : value) / 32768;
	}
	return data;
}

const recordings: ReadonlyArray<BakedRecording> = ${JSON.stringify(recordings, null, "\t")};

SampleRegistry.batch((): void => {
	for (const recording of recordings) {
		try {
			const zone = {keyLow: 0, keyHigh: 127, rootKey: recording.rootKey, sampleRate: recording.sampleRate, data: decode(recording.pcm), loopStart: recording.loopStart, loopEnd: recording.loopEnd};
			SampleRegistry.register(recording.name, [zone], {category: "sampled", isNoise: recording.isNoise});
		} catch (error) {
			console.error("Couldn't load the recording \\"" + recording.name + "\\":", error);
		}
	}
});
`;
	}
	const previous = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : null;
	if (previous != output) fs.writeFileSync(outputPath, output);
}

main();
